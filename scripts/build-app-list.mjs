// Builds the automatic part of the app list, and a teacher explainer page for every app.
//
//   node scripts/build-app-list.mjs            fetch repos from GitHub, write data/repos.json, then the pages
//   node scripts/build-app-list.mjs --offline  skip GitHub; just (re)write the explainer pages
//
// A repo is listed when it has the topic "walshclassroom" and GitHub Pages turned on.
// If the repo has a walshclassroom.json file at its root, those fields are used too.
// Runs every day in GitHub Actions (.github/workflows/app-list.yml). Needs Node 18+.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OWNER = process.env.WC_OWNER || 'twalsh95';
const TOPIC = 'walshclassroom';
const offline = process.argv.includes('--offline');

async function gh(url) {
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'walshclassroom-app-list' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const r = await fetch(url, { headers });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

async function fetchRepos() {
  const q = encodeURIComponent(`user:${OWNER} topic:${TOPIC}`);
  const res = await gh(`https://api.github.com/search/repositories?q=${q}&per_page=100`);
  const apps = [];
  for (const repo of res.items) {
    if (!repo.has_pages || repo.archived || repo.private) continue;
    let manifest = null;
    try {
      const r = await fetch(`https://raw.githubusercontent.com/${repo.full_name}/${repo.default_branch}/walshclassroom.json`);
      if (r.ok) manifest = await r.json();
    } catch (e) { console.warn(`Bad walshclassroom.json in ${repo.name}: ${e.message}`); }
    apps.push({ id: repo.name, description: repo.description || '', updated: repo.pushed_at, manifest });
  }
  apps.sort((a, b) => a.id.localeCompare(b.id));
  return apps;
}

function readOverrides() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'apps.js'), 'utf8'), ctx);
  return ctx.window.WC_APPS || [];
}

const idFromHref = h => (/^\/([^/?#]+)\/?/.exec(h || '') || [])[1];

function explainerShell(id) {
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>For teachers | Walsh Classroom</title>
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=Unbounded:wght@700;800&family=Young+Serif&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/assets/wc.css">
</head>
<body>
  <!-- Generated by scripts/build-app-list.mjs. Edit the explainer in apps.js (the "about" field), not here. -->
  <a class="skip" href="#main">Skip to content</a>
  <header id="site-header"></header>
  <main id="main"></main>
  <footer id="site-footer"></footer>
  <script>window.WC_PAGE = { type: "explainer", app: ${JSON.stringify(id)} };</script>
  <script src="/platform/wc.js" data-bar="off"></script>
  <script src="/assets/site.js"></script>
  <script src="/assets/pages.js"></script>
</body>
</html>
`;
}

let generated;
if (offline) {
  const f = path.join(ROOT, 'data', 'repos.json');
  generated = fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')).apps : [];
} else {
  generated = await fetchRepos();
  fs.mkdirSync(path.join(ROOT, 'data'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'data', 'repos.json'), JSON.stringify({ topic: TOPIC, apps: generated }, null, 2) + '\n');
  console.log(`data/repos.json: ${generated.length} repo(s) tagged "${TOPIC}"`);
}

// One explainer page per app that has an "about" section (from apps.js or the repo's walshclassroom.json).
const ids = new Set();
for (const g of generated) if (g.manifest && g.manifest.about && !g.manifest.hidden) ids.add(g.id);
for (const a of readOverrides()) {
  const id = a.id || idFromHref(a.href);
  if (!id) continue;
  if (a.about && !a.hidden) ids.add(id); else if (a.hidden) ids.delete(id);
}
for (const id of ids) {
  const dir = path.join(ROOT, 'teachers', id);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), explainerShell(id));
  console.log(`teachers/${id}/index.html`);
}
